    '| 전체 명령 | `vhk help --all` | 마케팅·커머스 명령까지 전부 |',
    '',
    '## 매일 쓰는 명령어',
    '',
    '| 하고 싶은 것 | 터미널 명령 | AI에게 말하기 |',
    '|-------------|-----------|------------------|',
    '| 저장 | `vhk save` | "저장해" |',
    '| 오늘 정리 | `vhk 정리` | "오늘 한 일 정리해" |',
    '| 규칙 점검 | `vhk 점검` | "규칙 점검해" |',
    '| 보안 스캔 | `vhk 보안 scan` | "보안 스캔 돌려" |',
    buildTestRow,
    '| 배포 | `vhk 배포` | "배포해" |',
