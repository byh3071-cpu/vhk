    '',
    '## 새 프로젝트 시작',
    '',
    '| 하고 싶은 것 | 터미널 명령 | AI에게 말하기 |',
    '|-------------|-----------|------------------|',
    '| 새 프로젝트 시작 (올인원) | `vhk start` | "새 프로젝트 시작해줘" |',
    '| 기술 스택을 바로 확정 | `vhk start --stack "Vite, React, TypeScript"` | "이 기술 스택으로 시작해줘" |',
    '',
    '> `vhk start` 하나로 `git init` + 문서 생성 + Cursor MCP 등록 + AI 컨텍스트 생성을 한 번에 처리합니다.',
    '> `--stack`을 지정하면 기술 스택을 확정하고, 미지정하면 자동 감지·유형 프리셋을 후보로 기록해 첫 세션에서 확인합니다.',
    '',
    '## 도움말',
