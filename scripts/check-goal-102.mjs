#!/usr/bin/env node
// scripts/check-goal-102.mjs — 자동 생성 (vhk goal sync).
// 기본 게이트 = typecheck + (lint) + test + build. goal 고유 검증은 아래 구역에 추가.
// sync 재실행해도 기존 파일은 덮어쓰지 않습니다 (idempotent).
//
// Env: VHK_GATES_SKIP_DEEP=1  → test + build 스킵 (빠른 typecheck-only 패스)

import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync } from 'node:fs'

const SHIM = new Set(['pnpm', 'npm', 'npx', 'yarn'])
// cmd.exe /c 래핑 경로는 따옴표+&|<>^% 조합 인자로 인용 경계를 탈출당할 수 있다(CVE-2024-27980
// 과 같은 근본원인 클래스, src/lib/exec.ts 실증) — 위험 문자 있으면 거부(fail-closed).
const CMD_SHELL_METACHARS = /[&|<>^%"\r\n]/
function run(cmd, args) {
  let bin = cmd, argv = args
  if (process.platform === 'win32' && SHIM.has(cmd)) {
    const bad = args.find((a) => CMD_SHELL_METACHARS.test(a))
    if (bad !== undefined) {
      console.log('안전하지 않은 인자 거부 — cmd.exe 특수문자 포함: ' + JSON.stringify(bad))
      return false
    }
    // Windows: .cmd shim 직접 spawn 은 Node CVE-2024-27980 으로 EINVAL → cmd.exe 래핑.
    bin = 'cmd.exe'; argv = ['/d', '/s', '/c', cmd + '.cmd', ...args]
  }
  try {
    // maxBuffer 상향: 큰 빌드/테스트 로그(>1MB)에서 성공해도 ENOBUFS 거짓실패 방지.
    execFileSync(bin, argv, { stdio: ['pipe', 'pipe', 'pipe'], encoding: 'utf-8', maxBuffer: 64 * 1024 * 1024 })
    return true
  } catch (e) {
    const out = (e?.stdout?.toString() ?? '') + (e?.stderr?.toString() ?? '')
    if (out.trim()) console.log(out.split('\n').slice(-25).join('\n'))
    return false
  }
}

if (existsSync('.vhk/HARD_STOP')) {
  console.log('🛑 .vhk/HARD_STOP detected — refusing to run goal 102 gate.')
  process.exit(1)
}

// BOM-safe 읽기: PowerShell Set-Content -Encoding utf8 의 UTF-8 BOM 제거(없으면 throw).
const readJson = (p) => { const t = readFileSync(p, 'utf-8'); return JSON.parse(t.charCodeAt(0) === 0xfeff ? t.slice(1) : t) }
const pkg = existsSync('package.json') ? readJson('package.json') : {}
const scripts = pkg.scripts ?? {}
const pm = existsSync('pnpm-lock.yaml') ? 'pnpm' : existsSync('yarn.lock') ? 'yarn' : 'npm'
const skipDeep = process.env.VHK_GATES_SKIP_DEEP === '1'
let pass = true
const gate = (label, ok) => { console.log('[goal 102] ' + label + ': ' + (ok ? '✓' : '✗')); if (!ok) pass = false }
const must = (cond, label) => { console.log((cond ? '    ✓ ' : '    ✗ ') + label); if (!cond) pass = false }

// typecheck (스크립트 우선, 없으면 tsc --noEmit)
if (scripts.typecheck) gate('typecheck', run(pm, ['run', 'typecheck']))
else if (existsSync('tsconfig.json')) gate('tsc --noEmit', run(pm, pm === 'npm' ? ['exec', '--', 'tsc', '--noEmit'] : ['exec', 'tsc', '--noEmit']))
if (scripts.lint) gate('lint', run(pm, ['run', 'lint']))
if (!skipDeep) {
  if (scripts['test:run']) gate('test', run(pm, ['run', 'test:run']))
  else if (scripts.test && /vitest/.test(scripts.test)) gate('test', run(pm, ['run', 'test', '--', '--run']))
  else if (scripts.test) gate('test', run(pm, ['run', 'test']))
  if (scripts.build) gate('build', run(pm, ['run', 'build']))
}

// ─── goal 102 고유 검증 (직접 추가) ───────────────────────────────
const read = (p) => existsSync(p) ? readFileSync(p, 'utf-8') : null

const skill = read('.claude/skills/overnight-vhk-auto/SKILL.md')
must(!!skill, 'overnight-vhk-auto/SKILL.md 존재')
must(/auto_pr_goal/i.test(skill ?? ''), 'overnight 스킬이 auto_pr_goal 호출')
must(/-BaseBranch\s+main/i.test(skill ?? ''), 'overnight 스킬의 BaseBranch=main')
must(/HARD_STOP/.test(skill ?? ''), 'overnight 스킬이 HARD_STOP 계약')
must(/NOT_STARTED|Wave B|105/i.test(skill ?? ''), 'overnight 큐가 DONE Wave A 재실행이 아니라 NOT_STARTED/Wave B')
must(/Merge = 0|머지.*0|never merge|Merge forbidden/i.test(skill ?? ''), 'overnight 스킬이 머지 금지')
must(/autonomy-log|INV-9|INV-C/.test(skill ?? ''), 'overnight 스킬이 autonomy-log 누락→HARD_STOP')
must(!/overnight-autoloop/.test(skill ?? '') || /do not mix|혼용 금지|Different track/i.test(skill ?? ''), 'overnight-autoloop 혼용 금지 명시')

const runbook = read('docs/runbooks/overnight-vhk-auto.md')
must(!!runbook, 'docs/runbooks/overnight-vhk-auto.md 존재')
must(/overnight-vhk-auto\/SKILL\.md/.test(runbook ?? ''), '런북이 스킬 교차 링크')
must(skill?.includes('docs/runbooks/overnight-vhk-auto.md'), '스킬이 런북 교차 링크')

const rfc = read('docs/rfc/0063-overnight-vhk-auto.md')
must(!!rfc, 'RFC 0063 Draft 존재')

if (pass) { console.log('✅ goal 102 gate passes'); process.exit(0) }
console.log('❌ goal 102 gate failed'); process.exit(1)
