#!/usr/bin/env node
// scripts/gen-goals-index.mjs — goals/README.md 자동 생성 (governance-v2 T2).
// goal 카드 frontmatter(번호·한국어 title·status·priority·leads_to)를 표로 모아
// 61+ 파일 탐색성을 해결한다(파일 리네임 없이 한국어 가시성 — spec Non-goal 준수).
//
// 사용: node scripts/gen-goals-index.mjs [goalsDir=goals] [out=<goalsDir>/README.md]
// 주의: src/lib/goal-frontmatter.ts(listGoals)와 같은 flat key:value 규칙의 .mjs 미니 파서 —
//       tsup 이 dist 를 번들(entry 2개)로만 내서 .mjs 가 TS 모듈을 import 할 수 없음(_lib.mjs 선례).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, basename } from 'node:path'
import { pathToFileURL } from 'node:url'

/** flat `key: value` frontmatter 파싱. 블록 없으면 null. 값은 전부 string 보존. */
export function parseFlatFrontmatter(md) {
  const text = md.charCodeAt(0) === 0xfeff ? md.slice(1) : md
  const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text)
  if (!m) return null
  const out = {}
  for (const raw of m[1].split(/\r?\n/)) {
    const line = raw.trim()
    if (!line || line.startsWith('#')) continue
    const idx = line.indexOf(':')
    if (idx <= 0) continue
    out[line.slice(0, idx).trim()] = line.slice(idx + 1).trim()
  }
  return out
}

/** goals 디렉토리에서 유효 goal(type:goal + 숫자 id)만 수집, id 오름차순. */
export function collectGoals(goalsDir) {
  let entries
  try {
    entries = readdirSync(goalsDir)
  } catch {
    return []
  }
  const goals = []
  for (const name of entries) {
    if (!name.endsWith('.md') || name === 'README.md') continue
    let fm
    try {
      fm = parseFlatFrontmatter(readFileSync(join(goalsDir, name), 'utf-8'))
    } catch {
      continue
    }
    if (!fm || fm.type !== 'goal') continue
    const id = Number(fm.id)
    if (!Number.isFinite(id)) continue
    goals.push({
      id,
      file: name,
      title: fm.title ?? '(제목 없음)',
      status: fm.status ?? 'NOT_STARTED',
      priority: fm.priority ?? '',
      leads_to: fm.leads_to ?? '',
    })
  }
  goals.sort((a, b) => a.id - b.id)
  return goals
}

const STATUS_ICON = { DONE: '✅', IN_PROGRESS: '🔄', NOT_STARTED: '⬜', BLOCKED: '⛔' }

function cell(v) {
  return String(v).replace(/\|/g, '\\|')
}

export function buildGoalsIndex(goals) {
  const counts = {}
  for (const g of goals) counts[g.status] = (counts[g.status] ?? 0) + 1
  const summary = Object.entries(counts)
    .map(([s, n]) => `${s} ${n}`)
    .join(' · ')

  const lines = [
    '<!-- AUTO-GENERATED by scripts/gen-goals-index.mjs — 수동 편집 금지. 재생성: node scripts/gen-goals-index.mjs -->',
    '',
    '# goals/ 인덱스',
    '',
    `> 총 ${goals.length} goal — ${summary}`,
    '> 공통 게이트 = [_meta.md](_meta.md) · 카드 형식/상태 의미는 각 파일 frontmatter 참조.',
    '',
    '| # | 제목 | 상태 | 우선순위 | 다음 연결 |',
    '|--:|------|:----:|:--------:|-----------|',
  ]
  for (const g of goals) {
    const icon = STATUS_ICON[g.status] ?? ''
    lines.push(
      `| ${g.id} | ${cell(g.title)} | ${icon} ${cell(g.status)} | ${cell(g.priority)} | ${cell(g.leads_to)} |`
    )
  }
  lines.push('')
  return lines.join('\n')
}

function main() {
  const goalsDir = process.argv[2] || 'goals'
  const out = process.argv[3] || join(goalsDir, 'README.md')
  const goals = collectGoals(goalsDir)
  writeFileSync(out, buildGoalsIndex(goals), 'utf-8')
  console.log(`[gen-goals-index] ${basename(out)} 생성 — goal ${goals.length}건`)
}

const isMain = process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url
if (isMain) main()
